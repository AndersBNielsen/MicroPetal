import {bundle} from '@remotion/bundler';
import {renderMedia,renderStill,selectComposition} from '@remotion/renderer';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));process.chdir(root);
const serveUrl=await bundle({entryPoint:path.join(root,'src/index.tsx'),publicDir:path.join(root,'public')});
const options={serveUrl,browserExecutable:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'};
const composition=await selectComposition({...options,id:'Song'});let previous=-1;
await renderMedia({...options,composition,codec:'h264',audioCodec:'aac',crf:18,concurrency:4,outputLocation:'out/revision2/micropetal-song.mp4',onProgress:({progress})=>{const pct=Math.floor(progress*10)*10;if(pct!==previous){console.log(`Song ${pct}%`);previous=pct;}}});
for(let i=0;i<12;i++)await renderStill({...options,composition,frame:Math.floor((i+.5)*composition.durationInFrames/12),output:`out/revision2/song-scene-${i}.png`});
